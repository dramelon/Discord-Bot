/**
 * Escapes HTML tag brackets and ampersands to prevent XSS while leaving safe characters intact.
 * @param {any} val 
 * @returns {string}
 */
function sanitizeInput(val) {
	if (val === null || val === undefined) return '';
	const text = typeof val !== 'string' ? String(val) : val;
	return text
		.replace(/&/g, '&amp;')
		.replace(/</g, '&lt;')
		.replace(/>/g, '&gt;');
}

